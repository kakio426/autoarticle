# 🛠️ 더미 이미지 생성 함수
def create_dummy_image(text, filename):
    img = Image.new('RGB', (800, 600), color=(255, 245, 230))
    d = ImageDraw.Draw(img)
    # 한글 폰트가 없을 수 있으므로 상자로 대체하거나 시스템 폰트 시도
    try:
        # Windows 기준 폰트 경로
        font = ImageFont.truetype("malgun.ttf", 40)
    except:
        font = None
    
    d.rectangle([20, 20, 780, 580], outline=(255, 140, 66), width=5)
    d.text((100, 250), text, fill=(50, 50, 50), font=font)
    
    path = os.path.join(IMAGE_DIR, filename)
    img.save(path)
    return path

